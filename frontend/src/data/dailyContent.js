export function dailyIndex(length, offset = 0) {
  const baliDate = new Date().toLocaleDateString('en-CA', { timeZone: 'Asia/Makassar' })
  const day = Math.floor(Date.parse(`${baliDate}T00:00:00Z`) / 86400000)
  return (day + offset) % length
}
